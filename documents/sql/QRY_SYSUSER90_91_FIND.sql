CREATE OR ALTER PROCEDURE QRY_SYSUSER90_91_FIND (
    CODIGO VARCHAR(50) CHARACTER SET ISO8859_1 COLLATE ISO8859_1)
RETURNS (
    ID_SYSUSER99 BIGINT,
    SYSUSER99_REMITENTE VARCHAR(1200) CHARACTER SET ISO8859_1 COLLATE ISO8859_1,
    SYSUSER99_FAPL TIMESTAMP)
AS
DECLARE VARIABLE V_CODIGO VARCHAR(50);
BEGIN
    V_CODIGO = TRIM(UPPER(COALESCE(CODIGO, '')));

    ID_SYSUSER99 = NULL;
    SYSUSER99_REMITENTE = NULL;
    SYSUSER99_FAPL = NULL;

    IF (SUBSTRING(V_CODIGO FROM 1 FOR 2) = 'SF') THEN
    BEGIN
        SELECT FIRST 1
            I.ID_SYSUSER90,
            TRIM(TRIM(U.SYSUSER10_NOMBRES) || ' ' ||
                 TRIM(U.SYSUSER10_APELLIDOS)),
            I.SYSUSER90_FAPL
        FROM SYSUSER90_TBL_SALDIFY I
        INNER JOIN SYSUSER10_CAB_MOVIL U
            ON TRIM(LOWER(U.SYSUSER10_UUID)) =
               TRIM(LOWER(I.SYSUSER90_ANFITRION_UUID))
        WHERE TRIM(UPPER(I.SYSUSER90_CODIGO)) = :V_CODIGO
        INTO
            :ID_SYSUSER99,
            :SYSUSER99_REMITENTE,
            :SYSUSER99_FAPL;
    END
    ELSE IF (SUBSTRING(V_CODIGO FROM 1 FOR 2) = 'SY') THEN
    BEGIN
        SELECT FIRST 1
            I.ID_SYSUSER91,
            TRIM(TRIM(U.SYSUSER10_NOMBRES) || ' ' ||
                 TRIM(U.SYSUSER10_APELLIDOS)),
            I.SYSUSER91_FAPL
        FROM SYSUSER91_TBL_LEALTAD I
        INNER JOIN SYSUSER10_CAB_MOVIL U
            ON U.ID_SYSUSER10 = I.RELA_SYSUSER10
        WHERE TRIM(UPPER(I.SYSUSER91_CODIGO)) = :V_CODIGO
        INTO
            :ID_SYSUSER99,
            :SYSUSER99_REMITENTE,
            :SYSUSER99_FAPL;
    END

    IF (ID_SYSUSER99 IS NOT NULL) THEN
        SUSPEND;
END^

SET TERM ; ^
